// CountryCode переводит имя или код страны в ISO 3166-1 alpha-2.
//
// Параметры: raw — код или английское имя.
// Результат: код в верхнем регистре и true, если значение известно. Известный псевдоним ищется раньше двух букв, поэтому uk даёт GB. Прочий двухбуквенный код принимается как есть.
// Ошибки: нет. Неизвестное имя даёт пустую строку и false.
func CountryCode(raw string) (string, bool) {
	s := strings.TrimSpace(raw)
	if s == "" {
		return "", false
	}
	if code, ok := countryByName[strings.ToLower(s)]; ok {
		return code, true
	}
	if len(s) == 2 && isAlpha(s) {
		return strings.ToUpper(s), true
	}
	return "", false
}
